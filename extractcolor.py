from google.colab import files
from PIL import Image
import colorgram
import numpy as np

# Get da picture
uploadedImage = files.upload()
image_path = list(uploadedImage.keys())[0]
# Configure NumPy to print without wrapping lines so the matrix layout looks perfect
np.set_printoptions(linewidth=200)

print("We will pull the most dominant colors from your image.")
while True:
  try:
    colorExtractCount = int(input("But first, how many colors should be pulled? Input: "))
    print(f"Alright, {colorExtractCount} colors it is")
    break
  except ValueError:
    print("Input needs to be a number, try again.")

# Open the image and resize it to speed up color extraction.
with Image.open(image_path) as img:
    # Resize to max 200px on either side preserving aspect ratio.
    img.thumbnail((200, 200))

    # Extract colors.
    pallet = colorgram.extract(img, colorExtractCount)

# Use the actual number of extracted colors (in case colorgram returns fewer than requested)
actual_count = len(pallet)

# save the colors to a matrix. actual_count by 3.
color_matrix = np.zeros((actual_count, 3), dtype=int)
for i, color in enumerate(pallet):
    color_matrix[i, 0] = color.rgb.r
    color_matrix[i, 1] = color.rgb.g
    color_matrix[i, 2] = color.rgb.b

print(f"\nExtracted Color Matrix ({actual_count} x 3):")
print("Rows represent individual colors. Columns are [Red, Green, Blue]")
print(color_matrix)

print("\n RGB values:")
for i, color in enumerate(pallet):
  print(f"Color number: {i + 1} has the rgb values: {color.rgb}. It takes up ~{round(color.proportion * 100, 2)}% of the image.")

